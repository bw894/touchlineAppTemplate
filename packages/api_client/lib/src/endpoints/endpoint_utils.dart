// ignore_for_file: non_constant_identifier_names
import 'dart:convert';

// kDebugMode equivalent in pure Dart (no flutter/foundation.dart needed)
const bool kDebugMode = !bool.fromEnvironment('dart.vm.product');

String _toEncodable(dynamic item) {
  return item;
}

// ignore: library_private_types_in_public_api
String serializeList(List? list) {
  list ??= <String>[];
  try {
    return json.encode(list, toEncodable: _toEncodable);
  } catch (_) {
    if (kDebugMode) {
      print("List serialization failed. Returning empty list.");
    }
    return '[]';
  }
}

// ignore: library_private_types_in_public_api
String serializeJson(dynamic jsonVar, [bool isList = false]) {
  jsonVar ??= (isList ? [] : {});
  try {
    return json.encode(jsonVar, toEncodable: _toEncodable);
  } catch (_) {
    if (kDebugMode) {
      print("Json serialization failed. Returning empty json.");
    }
    return isList ? '[]' : '{}';
  }
}

String? escapeStringForJson(String? input) {
  if (input == null) {
    return null;
  }
  return input
      .replaceAll('\\', '\\\\')
      .replaceAll('"', '\\"')
      .replaceAll('\n', '\\n')
      .replaceAll('\t', '\\t');
}
